import 'package:flutter/material.dart';

/// Canonical menu icon roles. Every role points to the existing Flutter
/// Material Symbols collection already used by LIFE OS. Swapping the icon
/// library later changes this file, not feature screens.
enum AppMenuIconRole {
  planning,
  notes,
  categories,
  notifications,
  viktor,
  connections,
  health,
  appearance,
  account,
  about,
  paths,
  people,
  calendar,
  clock,
  schedule,
  link,
  shield,
  microphone,
  desktop,
  tags,
  list,
  folder,
  theme,
  language,
  search,
  sync,
  defaultTime,
  filter,
  feedback,
  arrow,
  back,
  close,
}

abstract final class AppMenuIcons {
  static IconData icon(AppMenuIconRole role) => switch (role) {
    AppMenuIconRole.planning => Icons.event_note_outlined,
    AppMenuIconRole.notes => Icons.sticky_note_2_outlined,
    AppMenuIconRole.categories => Icons.sell_outlined,
    AppMenuIconRole.notifications => Icons.notifications_none_rounded,
    AppMenuIconRole.viktor => Icons.auto_awesome_outlined,
    AppMenuIconRole.connections => Icons.hub_outlined,
    AppMenuIconRole.health => Icons.favorite_border_rounded,
    AppMenuIconRole.appearance => Icons.palette_outlined,
    AppMenuIconRole.account => Icons.person_outline_rounded,
    AppMenuIconRole.about => Icons.info_outline_rounded,
    AppMenuIconRole.paths => Icons.alt_route_rounded,
    AppMenuIconRole.people => Icons.people_outline_rounded,
    AppMenuIconRole.calendar => Icons.calendar_month_outlined,
    AppMenuIconRole.clock => Icons.schedule_rounded,
    AppMenuIconRole.schedule => Icons.timeline_rounded,
    AppMenuIconRole.link => Icons.link_rounded,
    AppMenuIconRole.shield => Icons.shield_outlined,
    AppMenuIconRole.microphone => Icons.mic_none_rounded,
    AppMenuIconRole.desktop => Icons.desktop_windows_outlined,
    AppMenuIconRole.tags => Icons.label_outline_rounded,
    AppMenuIconRole.list => Icons.format_list_bulleted_rounded,
    AppMenuIconRole.folder => Icons.folder_outlined,
    AppMenuIconRole.theme => Icons.brightness_6_outlined,
    AppMenuIconRole.language => Icons.language_rounded,
    AppMenuIconRole.search => Icons.search_rounded,
    AppMenuIconRole.sync => Icons.sync_rounded,
    AppMenuIconRole.defaultTime => Icons.timer_outlined,
    AppMenuIconRole.filter => Icons.tune_rounded,
    AppMenuIconRole.feedback => Icons.feedback_outlined,
    AppMenuIconRole.arrow => Icons.chevron_right_rounded,
    AppMenuIconRole.back => Icons.arrow_back_rounded,
    AppMenuIconRole.close => Icons.close_rounded,
  };
}
