String normalize(String value) {
  final buffer = StringBuffer();
  var pendingSpace = false;
  for (final rune in value.runes) {
    final whitespace = rune == 9 || rune == 10 || rune == 13 || rune == 32;
    if (whitespace) {
      pendingSpace = buffer.isNotEmpty;
      continue;
    }
    if (pendingSpace) {
      buffer.write(' ');
      pendingSpace = false;
    }
    buffer.writeCharCode(rune);
  }
  return buffer.toString().trim();
}

List<NoteBlock> legacySelection(List<NoteBlock> textBlocks, String plain) {
  if (plain.isEmpty) return const <NoteBlock>[];
    if (textBlocks.isEmpty) return const <NoteBlock>[];
    final normalizedSelection = normalize(plain);
    List<NoteBlock>? wholeBlockBest;
    for (var start = 0; start < textBlocks.length; start++) {
      for (var end = start; end < textBlocks.length; end++) {
        final window = textBlocks.sublist(start, end + 1);
        final candidate = normalize(
window.map((block) => block.effectiveText).join('\n'),
        );
        if (candidate != normalizedSelection) continue;
        final preservesMeaning =
  window.length > 1 || window.single.type != NoteBlockType.paragraph;
        if (!preservesMeaning) continue;
        if (wholeBlockBest == null || window.length < wholeBlockBest.length) {
wholeBlockBest = List<NoteBlock>.from(window);
        }
      }
    }
    if (wholeBlockBest != null) return wholeBlockBest;
    List<NoteBlock>? best;
    var bestWindow = 1 << 30;
    for (var startIndex = 0; startIndex < textBlocks.length; startIndex++) {
      final buffer = StringBuffer();
      final offsets = <int>[0];
      for (
        var endIndex = startIndex;
        endIndex < textBlocks.length;
        endIndex++
      ) {
        buffer.write(textBlocks[endIndex].effectiveText);
        offsets.add(buffer.length);
        if (buffer.length < plain.length) continue;
        final joined = buffer.toString();
        var searchFrom = 0;
        while (searchFrom <= joined.length - plain.length) {
          final foundAt = joined.indexOf(plain, searchFrom);
          if (foundAt < 0) break;
          final selectedEnd = foundAt + plain.length;
          final slices = <NoteBlock>[];
          for (
            var localIndex = 0;
            localIndex <= endIndex - startIndex;
            localIndex++
          ) {
            final source = textBlocks[startIndex + localIndex];
            final blockStart = offsets[localIndex];
            final blockEnd = offsets[localIndex + 1];
            final overlapStart = foundAt > blockStart ? foundAt : blockStart;
            final overlapEnd = selectedEnd < blockEnd ? selectedEnd : blockEnd;
            if (overlapStart >= overlapEnd) continue;
            final localStart = overlapStart - blockStart;
            final localEnd = overlapEnd - blockStart;
            if (localStart == 0 && localEnd == source.effectiveText.length) {
              slices.add(source);
            } else {
              slices.add(
                source.copyWith(
                  text: source.effectiveText.substring(localStart, localEnd),
                  runs: const <NoteTextRun>[],
                ),
              );
            }
          }
          // A single selected text fragment should behave like normal clipboard
          // text. Structure matters once selection crosses a block boundary.
          if (slices.length >= 2) {
            final window = endIndex - startIndex + 1;
            if (window < bestWindow) {
              best = slices;
              bestWindow = window;
            }
          }
          searchFrom = foundAt + 1;
        }
        if (bestWindow == 2) break;
      }
      if (bestWindow == 2) break;
    }
    return best ?? const <NoteBlock>[];
}

void main() {
  test('Notes visual-only placeholder and list marker stay out of selection', () {
    final source = File(
      'lib/features/notes/widgets/note_editor_block_widgets.dart',
    ).readAsStringSync();

    expect(
      source,
      contains(
        'text.isEmpty\n              ? SelectionContainer.disabled(child: renderedText)\n              : renderedText',
      ),
      reason:
          'Empty-block hints such as "Write something" must remain visual-only and never enter SelectionArea clipboard text.',
    );
    expect(
      source,
      contains('SelectionContainer.disabled(child: marker)'),
      reason:
          'Rendered list markers are regenerated by structured clipboard export and must not contaminate SelectionArea text.',
    );
  });

  test('optimized clipboard selection matches legacy selection and tie order', () {
    final random = Random(20261127);
    const values = ['a', 'b', 'ab', 'ba', ' a ', '\t', '\n', '\u00a0a', 'a\u00a0', '😀'];
    List<String> signature(List<NoteBlock> rows) =>
        rows.map((row) => '${row.id}:${row.type}:${row.effectiveText}').toList();
    for (var trial = 0; trial < 400; trial++) {
      final blocks = List.generate(1 + random.nextInt(8), (i) => NoteBlock(
        id: 'b$i',
        type: random.nextBool() ? NoteBlockType.paragraph : NoteBlockType.heading,
        text: values[random.nextInt(values.length)],
      ));
      final joined = blocks.map((row) => row.effectiveText).join(
        random.nextBool() ? '' : '\n',
      );
      if (joined.isEmpty) continue;
      final start = random.nextInt(joined.length);
      final end = start + 1 + random.nextInt(joined.length - start);
      final plain = joined.substring(start, end);
      expect(
        signature(inferNotesClipboardSelection(blocks, plain, normalize)),
        signature(legacySelection(blocks, plain)),
        reason: 'trial $trial',
      );
    }
  });

  test('small selection in 2000 blocks avoids quadratic window enumeration', () {
    final blocks = List.generate(2000, (i) => NoteBlock(
      id: 'b$i', type: NoteBlockType.paragraph, text: 'row-$i',
    ));
    var calls = 0;
    final result = inferNotesClipboardSelection(blocks, '999row-1000', (s) {
      calls++;
      return normalize(s);
    });
    expect(result.map((row) => row.id), ['b999', 'b1000']);
    expect(calls, lessThan(4100));
  });
}
